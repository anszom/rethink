function makeDevice() {
    const ha = new MockHAConnection()
    const thinq = new MockThinq2Device(DEVICE_ID, META)
    const dev = new DUT(ha.asConnection(), thinq, META)
    return { ha, thinq, dev }
}

function feed(frames: Buffer[]) {
    const { ha, thinq } = makeDevice()
    for (const frame of frames) thinq.emit('data', frame)
    return ha.devices[DEVICE_ID].properties
}

describe('F3S1CWK__', () => {
    test('0xEB snapshot decodes as Standby with nothing selected', () => {
        const p = feed([EB_STANDBY])
        assert.equal(p.power, 'ON')
        assert.equal(p.status, 'Standby')
        assert.equal(p.course, 'None')
    })

    test('does not ack ordinary EB and EC status frames', () => {
        const { thinq } = makeDevice()
        thinq.emit('data', EB_STANDBY)
        thinq.emit('data', NORMAL)
        assert.deepEqual(thinq.sent, [])
    })

    test('dial walk decodes course, default settings and time', () => {
        let p = feed([NORMAL])
        assert.equal(p.course, 'Normal')
        assert.equal(p.remaining_time, 135)
        assert.equal(p.initial_time, 135)
        assert.equal(p.soil, 'Heavy')
        assert.equal(p.temp, 'Cool')
        assert.equal(p.spin, 'Medium High')
        assert.equal(p.turbo_wash, 'ON')
        assert.equal(p.extra_rinse, 'ON')
        assert.equal(p.extra_rinse_count, 1)
        assert.equal(p.rinse_count, 2)
        assert.equal(p.load_level, 0)

        p = feed([HEAVY_DUTY])
        assert.equal(p.course, 'Heavy Duty')
        assert.equal(p.remaining_time, 130)
        assert.equal(p.temp, 'Warm')
        assert.equal(p.spin, 'High')
        assert.equal(p.extra_rinse_count, 0)
        assert.equal(p.extra_rinse, 'OFF')

        p = feed([BEDDING])
        assert.equal(p.course, 'Bedding')
        assert.equal(p.remaining_time, 60)
        assert.equal(p.soil, 'Normal')
        assert.equal(p.load_level, 7)

        p = feed([SPEED_WASH])
        assert.equal(p.course, 'Speed Wash')
        assert.equal(p.remaining_time, 15)
        assert.equal(p.soil, 'Light')
        assert.equal(p.temp, 'Very Warm')

        p = feed([DELICATES])
        assert.equal(p.course, 'Delicates')
        assert.equal(p.remaining_time, 45)
    })

    test('the Downloaded position reports the course stored in it', () => {
        const p = feed([DOWNLOADED])
        assert.equal(p.course, 'Rinse + Spin')
        assert.equal(p.remaining_time, 18)
        assert.equal(p.soil, 'None')
    })

    test('temperature, spin and soil walks', () => {
        assert.equal(feed([TEMP_WARM]).temp, 'Warm')
        assert.equal(feed([TEMP_HOT]).temp, 'Very Warm')
        assert.equal(feed([TEMP_EXTRA_HOT]).temp, 'Hot')
        assert.equal(feed([TEMP_TAP_COLD]).temp, 'Cold')

        assert.equal(feed([SPIN_HIGH]).spin, 'High')
        assert.equal(feed([SPIN_LOW]).spin, 'Low')
        assert.equal(feed([SPIN_MEDIUM]).spin, 'Medium')
        assert.equal(feed([SPIN_MEDIUM_HIGH]).spin, 'Medium High')

        let p = feed([SOIL_LIGHT])
        assert.equal(p.soil, 'Light')
        assert.equal(p.remaining_time, 48)
        assert.equal(feed([SOIL_LIGHT_NORMAL]).soil, 'Light-Normal')
        assert.equal(feed([SOIL_NORMAL]).soil, 'Normal')
        p = feed([SOIL_NORMAL_HEAVY])
        assert.equal(p.soil, 'Normal-Heavy')
        assert.equal(p.remaining_time, 56)
    })

    test('options toggle without colliding', () => {
        let p = feed([STEAM_ON])
        assert.equal(p.steam, 'ON')
        assert.equal(p.soil, 'None')
        assert.equal(p.temp, 'None')
        assert.equal(feed([STEAM_ON, STEAM_OFF]).steam, 'OFF')

        p = feed([EXTRA_RINSE_2])
        assert.equal(p.extra_rinse_count, 2)
        assert.equal(p.rinse_count, 3)
        p = feed([EXTRA_RINSE_3])
        assert.equal(p.extra_rinse_count, 3)
        assert.equal(p.rinse_count, 4)
        p = feed([EXTRA_RINSE_OFF])
        assert.equal(p.extra_rinse, 'OFF')
        assert.equal(p.extra_rinse_count, 0)
        assert.equal(p.rinse_count, 1)

        p = feed([PRE_WASH_ON])
        assert.equal(p.pre_wash, 'ON')
        assert.equal(p.turbo_wash, 'ON')

        p = feed([REMOTE_ON])
        assert.equal(p.remote_start, 'ON')
        assert.equal(p.child_lock, 'OFF')
        assert.equal(feed([REMOTE_ON, REMOTE_OFF]).remote_start, 'OFF')

        p = feed([CONTROL_LOCK_ON])
        assert.equal(p.child_lock, 'ON')
        assert.equal(p.remote_start, 'OFF')
        assert.equal(feed([CONTROL_LOCK_ON, CONTROL_LOCK_OFF]).child_lock, 'OFF')

        assert.equal(feed([SIGNAL_OFF]).signal, 'Off')
        assert.equal(feed([SIGNAL_OFF, SIGNAL_HIGH]).signal, 'High')
    })

    test('long-press courses', () => {
        let p = feed([SANITARY])
        assert.equal(p.course, 'Sanitary')
        assert.equal(p.temp, 'Hot')

        p = feed([TUB_CLEAN])
        assert.equal(p.course, 'Tub Clean')
        assert.equal(p.steam, 'ON')
    })

    test('Rinse+Spin run with a pause, through End and the automatic power-off', () => {
        let p = feed([RINSE_SPIN_SELECTED, STARTING])
        assert.equal(p.status, 'Starting')

        p = feed([RINSE_SPIN_SELECTED, STARTING, RINSING])
        assert.equal(p.status, 'Rinsing')
        assert.equal(p.remote_start, 'ON')
        assert.equal(p.wash_completed, 'OFF')

        p = feed([RINSING, PAUSED])
        assert.equal(p.status, 'Paused')
        assert.equal(p.remote_start, 'OFF')

        p = feed([RINSING_15])
        assert.equal(p.remaining_time, 15)
        assert.equal(p.initial_time, 18)

        p = feed([SPINNING])
        assert.equal(p.status, 'Spinning')
        assert.equal(p.energy, 2)

        p = feed([SPINNING, END])
        assert.equal(p.status, 'End')
        assert.equal(p.wash_completed, 'ON')
        assert.equal(p.remaining_time, 0)
        assert.equal(p.remote_start, 'OFF')
        assert.equal(p.energy, 41)

        p = feed([SPINNING, END, END_TCL])
        assert.equal(p.tub_clean_count, 33)

        p = feed([SPINNING, END, END_TCL, AUTO_OFF])
        assert.equal(p.status, 'Off')
        assert.equal(p.power, 'OFF')
        assert.equal(p.wash_completed, 'ON')

        p = feed([SPINNING, END, END_TCL, AUTO_OFF, NORMAL])
        assert.equal(p.wash_completed, 'OFF')
    })

    // Both frames as the ThinQ app sent them while bridged; the washer answered each with AA083300E5009FBB.
    test('power off and on send the captured key/value commands', () => {
        const { thinq, dev } = makeDevice()
        dev.setProperty('power_off', 'PRESS')
        dev.setProperty('power_on', 'PRESS')
        dev.setProperty('power_on', 'not-a-press')
        assert.deepEqual(
            thinq.outbox.map((b) => b.toString('hex').toUpperCase()),
            ['AA0DF0E5000201FF010200C4BB', 'AA0DF0E5000201FF010201C7BB'],
        )
    })

    test('remote-control and dryer frames are ignored', () => {
        for (const junk of [
            'AA09337200C90074BB',
            'AA2434EB001C01000100010000000000040000000028020000000000006900000000F6BB',
        ]) {
            const { ha, thinq } = makeDevice()
            thinq.emit('data', buf(junk))
            assert.deepEqual(ha.devices[DEVICE_ID].properties, {})
        }
    })

    // Captured right after downloading Color Care from the ThinQ app: the old record still has Small Load
    // (0x69) stored, the current one Color Care (0x6f) on base course Normal (0x2e at rec[21]).
    test('the Downloaded position reports the course downloaded into it', () => {
        const p = feed([
            buf(
                'aa6033ec002b0003100e0fff00000000000000002d002d0000004401006900000002000400000000000004000000000000002b00030e0e0eff00000000000000002e002e0000002e01006f0000000100040000000020000400000001000045bb',
            ),
        ])
        assert.equal(p.course, 'Color Care')
        assert.equal(p.downloaded_course, 'Color Care')
    })
})
