    'AA7CF017FFFFFFFFFFFFFFFFFFFFFFFFFFFF00FFFFFFFFFFFF000000FFFF00FFFFFFFF00FFFFFFFFFFFFFFFFFF00FFFFFF1EFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFF0AFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFF00FFFFFFFFFFFFFFFFFFFFFFFFFFFFFFBCBB'
const APP_FRESH_AIR_RESET =
    'AA7CF017FFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFF000000FFFF00FFFFFFFF00FFFFFF64FFFFFFFFFF00FFFFFF1EFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFF0AFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFF00FFFFFFFFFFFFFFFFFFFFFFFFFFFFFF18BB'
const APP_WATER_FILTER_RESET =
    'AA7CF017FFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFF000000FFFF00FFFFFFFF00FFFFFFFF64FFFFFFFF00FFFFFF1EFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFF0AFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFF00FFFFFFFFFFFFFFFFFFFFFFFFFFFFFF18BB'

function makeDevice() {
    const ha = new MockHAConnection()
    const thinq = new MockThinq2Device(DEVICE_ID, META)
    const dev = new DUT(ha.asConnection(), thinq, META)
    return { ha, thinq, dev }
}

function props(ha: MockHAConnection) {
    return ha.devices[DEVICE_ID].properties
}

function lastSent(thinq: MockThinq2Device) {
    return thinq.outbox[thinq.outbox.length - 1].toString('hex').toUpperCase()
}

describe(MODEL_ID, () => {
    test('config waits for the temperature unit, then has no flex drawer', () => {
        const { ha, thinq } = makeDevice()
        assert.equal(ha.devices[DEVICE_ID]?.config, undefined)
        thinq.emit('data', FRAME_FRIDGE_38)
        const components = ha.devices[DEVICE_ID].config!.components as Record<string, Record<string, unknown>>
        assert.equal(components.fridge_setpoint.unit_of_measurement, '°F')
        assert.equal(components.flex_setpoint, undefined)
        for (const c of [
            'ice_plus',
            'sabbath_mode',
            'smart_learner',
            'water_filter',
            'fresh_air_filter',
            'water_dispensed',
        ])
            assert.ok(components[c], c)
    })

    test('setpoints decode from the captured app changes', () => {
        const { ha, thinq } = makeDevice()
        thinq.emit('data', FRAME_FRIDGE_38)
        assert.equal(props(ha).fridge_setpoint, 38)
        assert.equal(props(ha).freezer_setpoint, 0)
        thinq.emit('data', FRAME_FREEZER_1)
        assert.equal(props(ha).fridge_setpoint, 37)
        assert.equal(props(ha).freezer_setpoint, 1)
    })

    test('Ice Plus, door, Smart Learner and Sabbath decode', () => {
        const { ha, thinq } = makeDevice()
        thinq.emit('data', FRAME_ICE_PLUS_ON)
        assert.equal(props(ha).ice_plus, 'ON')
        assert.equal(props(ha).door, 'OFF')
        thinq.emit('data', FRAME_DOOR_OPEN)
        assert.equal(props(ha).door, 'ON')
        assert.equal(props(ha).ice_plus, 'OFF')
        thinq.emit('data', FRAME_SMART_LEARNER_ON)
        assert.equal(props(ha).smart_learner, 'ON')
        assert.equal(props(ha).sabbath_mode, 'OFF')
        thinq.emit('data', FRAME_SABBATH_ON)
        assert.equal(props(ha).sabbath_mode, 'ON')
    })

    test('filter life reads as a percent', () => {
        const { ha, thinq } = makeDevice()
        thinq.emit('data', FRAME_FRIDGE_38)
        assert.equal(props(ha).fresh_air_filter, 100)
        assert.equal(props(ha).water_filter, 100)
    })

    test('water dispensed comes from the 15-minute usage report, in litres', () => {
        const { ha, thinq } = makeDevice()
        thinq.emit('data', FRAME_FRIDGE_38)
        thinq.emit('data', FRAME_USAGE_GALLON)
        assert.equal(props(ha).water_dispensed, 7.818)
    })

    test('every command matches what the LG app sent, byte for byte', () => {
        const { dev, thinq } = makeDevice()
        thinq.emit('data', FRAME_FRIDGE_38)
        const cases: [string, string, string][] = [
            ['fridge_setpoint', '38', APP_FRIDGE_38],
            ['freezer_setpoint', '1', APP_FREEZER_1],
            ['ice_plus', 'ON', APP_ICE_PLUS_ON],
            ['ice_plus', 'OFF', APP_ICE_PLUS_OFF],
            ['smart_learner', 'ON', APP_SMART_LEARNER_ON],
            ['sabbath_mode', 'ON', APP_SABBATH_ON],
            ['sabbath_mode', 'OFF', APP_SABBATH_OFF],
            ['fresh_air_filter_reset', '', APP_FRESH_AIR_RESET],
            ['water_filter_reset', '', APP_WATER_FILTER_RESET],
        ]
        for (const [prop, value, expected] of cases) {
            dev.setProperty(prop, value)
            assert.equal(lastSent(thinq), expected, `${prop}=${value}`)
        }
    })
})
