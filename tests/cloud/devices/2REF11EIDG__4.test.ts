const DEVICE_ID = 'test-id'
const MODEL_ID = '2REF11EIDG__4'
const META: Metadata = { modelId: MODEL_ID, modelName: MODEL_ID, swVersion: '' }

// Every fixture below is a real frame captured from an LRFXC2606S (2REF11EIDG__4) through the
// rethink bridge, each change made from the LG app and confirmed by the LG cloud. The APP_* frames
// are the exact commands the LG app sent; the handler must reproduce them byte for byte.

// 10EC status deltas (previous block, then current block). The fridge starts at 37 °F / 0 °F,
// Ice Plus off, doors closed, °F, filters 100 %.
